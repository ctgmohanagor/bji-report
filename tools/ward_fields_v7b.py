# ফর্ম v7 → v7b: ওয়ার্ডের ঘর ছাপা-ফর্মের (পুরুষ/মহিলা) সাথে মেলানো। ইউনিট অপরিবর্তিত।
import json, sys, copy
src, out = sys.argv[1], sys.argv[2]
F = json.load(open(src, encoding='utf-8'))
by = {f['key']: f for f in F}

def add_opt(f, o):
    f['opt'] = (f['opt'] + ',' + o) if f.get('opt') else o

def gw(key, g, add_w=False):
    f = by[key]; f['gw'] = g
    if add_w and 'W' not in f['enter']:
        f['enter'] = ''.join(l for l in 'UWT' if l in f['enter'] + 'W')

def new(after, key, label, pattern=None, g='MF', enter='W', **kw):
    base = by[after]
    f = {'key': key, 'section': base['section'], 'sub': base['sub'], 'label': label, 'pattern': pattern or base['pattern'],
         'enter': enter, 'labels': [], 'src': '', 'only': '', 'note': '', 'opt': '', 'grp': base.get('grp', ''), 'lbl': False, 'gw': g}
    f.update(kw)
    F.insert(F.index(base) + 1 + sum(1 for x in F if x.get('_after') == after), f); f['_after'] = after
    by[key] = f
    return f

